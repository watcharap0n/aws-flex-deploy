CREATE FUNCTION identity.set_customer_member_app_scope() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $body$
DECLARE p record;
BEGIN
    SELECT app_id,source_system_id,source_customer_id INTO p
      FROM staging.customer_profile WHERE standardized_record_id=NEW.standardized_record_id;
    IF NOT FOUND OR (p.source_system_id,p.source_customer_id) IS DISTINCT FROM
        (NEW.source_system_id,NEW.source_customer_id) OR
        (NEW.app_id IS NOT NULL AND NEW.app_id IS DISTINCT FROM p.app_id) THEN
        RAISE EXCEPTION '050 member source/app tuple mismatch';
    END IF;
    NEW.app_id := p.app_id;
    RETURN NEW;
END $body$;
REVOKE ALL ON FUNCTION identity.set_customer_member_app_scope() FROM PUBLIC;
CREATE TRIGGER customer_member_app_scope BEFORE INSERT OR UPDATE ON identity.customer_entity_member
    FOR EACH ROW EXECUTE FUNCTION identity.set_customer_member_app_scope();
COMMENT ON COLUMN identity.customer_entity_member.app_id IS
 'Literal upload app lineage from active standardized profile; NULL includes unresolved historical manual uploads and connectors; never guessed from raw UUID.';
COMMIT;

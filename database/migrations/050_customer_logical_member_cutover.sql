-- Coordinated cutover of the ACTIVE staging/profile and identity member OIDs.
-- Requires paused writers/matcher/capture. Not a 038 activation: its stitch gate
-- must remain closed until every ordinary writer and reader is app-tuple aware.
-- Old standardized IDs and immutable observations/exports are never rewritten.
BEGIN;
SET LOCAL lock_timeout='10s';
-- Hard guards on a locked cutover; deployment still requires a measured lock window.
SET LOCAL statement_timeout='30min';
SET LOCAL work_mem='128MB';
SET LOCAL temp_file_limit='4GB';
LOCK TABLE raw.customer,raw.customer_batch_member,staging.customer_profile_history,
    staging.customer_profile,identity.customer_entity_member,
    control.ingestion_batch,control.customer_identity_transfer IN ACCESS EXCLUSIVE MODE;
-- Freeze immutable publication inserts while validating their exact mapping.
LOCK TABLE control.customer_identity_export IN SHARE MODE;
DO $lock_bridge$
BEGIN
    IF to_regclass('control.customer_identity_member_export') IS NOT NULL THEN
        LOCK TABLE control.customer_identity_member_export IN SHARE MODE;
    END IF;
END $lock_bridge$;
DO $preflight$
BEGIN
    IF to_regclass('raw.customer_logical_current') IS NOT NULL
       OR to_regclass('control.customer_forward_source_activation') IS NOT NULL
          AND to_regprocedure('raw.apply_customer_forward_bulk(uuid,bigint)') IS NULL
       OR to_regclass('staging.uq_customer_profile_raw_customer') IS NULL
       OR NOT EXISTS(SELECT FROM pg_constraint WHERE conrelid='identity.customer_entity_member'::regclass
           AND conname='customer_entity_member_source_system_id_source_customer_id_key'
           AND contype='u')
       OR to_regclass('staging.customer_profile_history') IS NULL
       OR to_regclass('identity.customer_entity_member') IS NULL
       OR EXISTS(SELECT FROM pg_attribute WHERE attrelid='identity.customer_entity_member'::regclass
           AND attname='app_id' AND NOT attisdropped) THEN
        RAISE EXCEPTION '050 incompatible catalog or already installed';
    END IF;
    IF EXISTS(SELECT FROM staging.customer_profile p
        JOIN identity.customer_entity_member m USING(standardized_record_id)
        WHERE (p.source_system_id,p.source_customer_id) IS DISTINCT FROM
              (m.source_system_id,m.source_customer_id)) THEN
        RAISE EXCEPTION '050 ambiguous legacy member/source tuple';
    END IF;
    IF EXISTS(SELECT FROM staging.customer_profile p
        WHERE p.app_id IS NOT NULL AND
          NOT EXISTS(SELECT FROM staging.customer_profile_history h
            WHERE (h.batch_id,h.raw_customer_id,h.app_id,h.source_system_id,h.source_customer_id)=
                  (p.batch_id,p.raw_customer_id,p.app_id,p.source_system_id,p.source_customer_id))) THEN
        RAISE EXCEPTION '050 ambiguous legacy current without exact typed history';
    END IF;
    IF EXISTS(SELECT FROM staging.customer_profile_history h
        LEFT JOIN control.ingestion_batch b ON b.batch_id=h.batch_id
        WHERE b.batch_id IS NULL OR h.app_id IS DISTINCT FROM b.app_id
          OR h.source_system_id IS DISTINCT FROM b.source_system_id
          OR NOT EXISTS(SELECT FROM raw.customer r WHERE
           r.batch_id=h.batch_id AND r.raw_customer_id=h.raw_customer_id
           AND (r.source_system_id,r.source_customer_id,r.app_id)
               IS NOT DISTINCT FROM
               (h.source_system_id,h.source_customer_id,h.app_id))) THEN
        RAISE EXCEPTION '050 ambiguous historical typed/batch/observation lineage';
    END IF;
    IF EXISTS(SELECT FROM staging.customer_profile_history h
        JOIN raw.customer_batch_member m ON
          (m.ingestion_batch_id,m.raw_customer_id)=(h.batch_id,h.raw_customer_id)
        WHERE (m.source_system_id,m.source_customer_id) IS DISTINCT FROM
              (h.source_system_id,h.source_customer_id)) THEN
        RAISE EXCEPTION '050 ambiguous historical immutable member tuple';
    END IF;
    IF EXISTS(SELECT FROM staging.customer_profile_history h
        LEFT JOIN raw.customer_batch_member m ON
          (m.ingestion_batch_id,m.raw_customer_id,m.source_system_id,m.source_customer_id)=
          (h.batch_id,h.raw_customer_id,h.source_system_id,h.source_customer_id)
        WHERE m.raw_customer_id IS NULL) THEN
        RAISE EXCEPTION '050 missing exact historical immutable member tuple';
    END IF;
    -- Every version is immutable evidence, not an assertion about today's
    -- active entity. The export ID was generated by the historical resolver,
    -- independently of the normalized history ID. Prove typed observation and
    -- bridge provenance instead of falsely equating either ID to history.
    IF EXISTS(SELECT FROM control.customer_identity_export e
        WHERE e.payload->>'app_id' IS DISTINCT FROM e.app_id
           OR e.payload->>'user_id' IS DISTINCT FROM e.user_id
           OR NOT EXISTS (SELECT FROM control.customer_identity_transfer transfer
               WHERE transfer.transfer_id=e.transfer_id AND transfer.status<>'BLOCKED')
           OR e.payload->>'source_system_id' !~ '^[0-9]+$'
           OR e.payload->>'raw_customer_id' !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
           OR e.payload->>'standardized_record_id' !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
           OR e.payload->>'customer_entity_id' !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
           OR NOT EXISTS (SELECT FROM staging.customer_profile_history h
               WHERE h.app_id=e.app_id AND h.source_customer_id=e.user_id
                 AND h.source_system_id::text=e.payload->>'source_system_id'
                 -- A guarded cast preserves fail-closed malformed payloads
                 -- while exposing the history (batch_id,raw_customer_id) index.
                 AND h.raw_customer_id=CASE WHEN
                     e.payload->>'raw_customer_id' !~*
                       '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
                     THEN NULL::uuid
                     ELSE (e.payload->>'raw_customer_id')::uuid END
                 AND EXISTS (SELECT FROM raw.customer_batch_member bm
                     WHERE (bm.ingestion_batch_id,bm.raw_customer_id,bm.source_system_id,bm.source_customer_id)=
                           (h.batch_id,h.raw_customer_id,h.source_system_id,h.source_customer_id)))
    ) THEN
        RAISE EXCEPTION '050 published export lacks exact immutable provenance';
    END IF;
    IF to_regclass('control.customer_identity_member_export') IS NOT NULL THEN
        IF EXISTS(SELECT FROM control.customer_identity_export e
            WHERE NOT EXISTS (SELECT FROM control.customer_identity_member_export me
                WHERE me.transfer_id=e.transfer_id AND me.app_id=e.app_id
                  AND me.source_customer_id=e.user_id
                  AND me.source_system_id::text=e.payload->>'source_system_id'
                  AND me.raw_customer_id::text=e.payload->>'raw_customer_id'
                  AND me.standardized_record_id::text=e.payload->>'standardized_record_id'
                  AND me.customer_entity_id::text=e.payload->>'customer_entity_id')) THEN
            RAISE EXCEPTION '050 published export lacks exact immutable member bridge';
        END IF;
        IF EXISTS(SELECT FROM control.customer_identity_member_export me
            WHERE NOT EXISTS (SELECT FROM staging.customer_profile_history h
                WHERE h.batch_id=me.batch_id AND h.raw_customer_id=me.raw_customer_id
                  AND (h.source_system_id,h.source_customer_id,h.app_id)
                  IS NOT DISTINCT FROM
                      (me.source_system_id,me.source_customer_id,me.app_id))
              OR NOT EXISTS (SELECT FROM raw.customer_batch_member bm
                WHERE (bm.ingestion_batch_id,bm.raw_customer_id,bm.source_system_id,bm.source_customer_id)=
                      (me.batch_id,me.raw_customer_id,me.source_system_id,me.source_customer_id))
              OR (me.app_id IS NOT NULL AND
                  (me.provenance_status NOT IN ('VERIFIED_UPLOAD','VERIFIED_CONNECTOR')
                   OR NOT EXISTS (SELECT FROM control.ingestion_batch b
                       WHERE b.batch_id=me.batch_id AND b.app_id=me.app_id
                         AND b.source_system_id=me.source_system_id)))) THEN
            RAISE EXCEPTION '050 published member export lacks exact immutable provenance';
        END IF;
    END IF;
    -- Validate mandatory fields before casting any ID in the reservation table.
    IF EXISTS (SELECT FROM control.customer_identity_export e
        WHERE e.payload->>'source_system_id' IS NULL
           OR e.payload->>'raw_customer_id' IS NULL
           OR e.payload->>'customer_entity_id' IS NULL
           OR e.payload->>'standardized_record_id' IS NULL
           OR e.payload->>'standardized_record_id' !~*
              '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$') THEN
        RAISE EXCEPTION '050 published mandatory provenance or ID malformed';
    END IF;
    -- The old published A resolver ID can also name B's current row. Keep
    -- historical publication and active identity disjoint: only the exact
    -- immutable A bridge and B's typed current batch may prove this alias.
    CREATE TEMP TABLE customer_050_published_active_alias (
        published_app text,published_user text,source_system_id bigint,
        raw_customer_id uuid,standardized_record_id uuid,active_app text
    ) ON COMMIT DROP;
    IF to_regclass('control.customer_identity_member_export') IS NOT NULL THEN
        INSERT INTO customer_050_published_active_alias
        SELECT DISTINCT e.app_id,e.user_id,me.source_system_id,me.raw_customer_id,
            me.standardized_record_id,p.app_id
        FROM control.customer_identity_export e
        JOIN control.customer_identity_transfer transfer ON transfer.transfer_id=e.transfer_id
            AND transfer.status='PUBLISHED'
        JOIN control.customer_identity_member_export me ON me.transfer_id=e.transfer_id
            AND me.app_id=e.app_id AND me.source_customer_id=e.user_id
            AND me.source_system_id::text=e.payload->>'source_system_id'
            AND me.raw_customer_id::text=e.payload->>'raw_customer_id'
            AND me.standardized_record_id::text=e.payload->>'standardized_record_id'
            AND me.customer_entity_id::text=e.payload->>'customer_entity_id'
        JOIN staging.customer_profile p ON p.standardized_record_id=me.standardized_record_id
            AND p.app_id IS NOT NULL AND p.app_id<>me.app_id
            AND (p.source_system_id,p.source_customer_id,p.raw_customer_id)=
                (me.source_system_id,me.source_customer_id,me.raw_customer_id)
        JOIN staging.customer_profile_history published_history ON
            (published_history.batch_id,published_history.raw_customer_id,
             published_history.source_system_id,published_history.source_customer_id,
             published_history.app_id)=
            (me.batch_id,me.raw_customer_id,me.source_system_id,me.source_customer_id,me.app_id)
        JOIN raw.customer_batch_member published_member ON
            (published_member.ingestion_batch_id,published_member.raw_customer_id,
             published_member.source_system_id,published_member.source_customer_id)=
            (me.batch_id,me.raw_customer_id,me.source_system_id,me.source_customer_id)
        JOIN staging.customer_profile_history active_history ON
            (active_history.batch_id,active_history.raw_customer_id,
             active_history.source_system_id,active_history.source_customer_id,
             active_history.app_id)=
            (p.batch_id,p.raw_customer_id,p.source_system_id,p.source_customer_id,p.app_id)
        JOIN raw.customer_batch_member active_member ON
            (active_member.ingestion_batch_id,active_member.raw_customer_id,
             active_member.source_system_id,active_member.source_customer_id)=
            (p.batch_id,p.raw_customer_id,p.source_system_id,p.source_customer_id)
        WHERE me.provenance_status IN ('VERIFIED_UPLOAD','VERIFIED_CONNECTOR')
          AND NOT EXISTS (SELECT FROM staging.customer_profile same_app
            WHERE same_app.app_id=me.app_id
              AND (same_app.source_system_id,same_app.source_customer_id)=
                  (me.source_system_id,me.source_customer_id)
              AND same_app.standardized_record_id<>me.standardized_record_id)
          AND NOT EXISTS (SELECT FROM staging.customer_profile_history conflicting
              WHERE conflicting.standardized_record_id=me.standardized_record_id
                AND (conflicting.app_id,conflicting.source_system_id,conflicting.source_customer_id)
                    IS DISTINCT FROM (me.app_id,me.source_system_id,me.source_customer_id));
    END IF;
    CREATE UNIQUE INDEX ON customer_050_published_active_alias(standardized_record_id);
    -- Export IDs are global reservations, even if the old operational row has
    -- since disappeared. Multiple versions of ONE tuple may use different IDs;
    -- no ID may claim two tuples, nor can an active profile steal one.
    IF EXISTS (SELECT FROM control.customer_identity_export e
        GROUP BY e.payload->>'standardized_record_id'
        HAVING count(DISTINCT (e.app_id,e.payload->>'source_system_id',e.user_id))>1)
       OR EXISTS (SELECT FROM control.customer_identity_export e
           JOIN staging.customer_profile p
             ON p.standardized_record_id=(e.payload->>'standardized_record_id')::uuid
           LEFT JOIN customer_050_published_active_alias alias
             ON alias.standardized_record_id=p.standardized_record_id
               AND (alias.published_app,alias.published_user,alias.source_system_id::text,
                    alias.raw_customer_id::text,alias.active_app)=
                   (e.app_id,e.user_id,e.payload->>'source_system_id',
                    e.payload->>'raw_customer_id',p.app_id)
           WHERE (p.app_id,p.source_system_id::text,p.source_customer_id)
             IS DISTINCT FROM (e.app_id,e.payload->>'source_system_id',e.user_id)
             AND alias.standardized_record_id IS NULL)
       OR EXISTS (SELECT FROM control.customer_identity_export e
           JOIN identity.customer_entity_member m
             ON m.standardized_record_id=(e.payload->>'standardized_record_id')::uuid
           WHERE (m.source_system_id::text,m.source_customer_id)
             IS DISTINCT FROM (e.payload->>'source_system_id',e.user_id)) THEN
        RAISE EXCEPTION '050 published standardized ID ownership collision';
    END IF;
    IF to_regclass('control.customer_identity_member_export') IS NOT NULL THEN
        IF EXISTS (SELECT FROM control.customer_identity_member_export me
            GROUP BY me.standardized_record_id
            HAVING count(DISTINCT (me.app_id,me.source_system_id,me.source_customer_id))>1)
           OR EXISTS (SELECT FROM control.customer_identity_member_export me
               JOIN control.customer_identity_export e
                 ON e.transfer_id=me.transfer_id
                AND me.standardized_record_id=CASE WHEN
                    e.payload->>'standardized_record_id' !~*
                      '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
                    THEN NULL::uuid ELSE (e.payload->>'standardized_record_id')::uuid END
               WHERE (me.app_id,me.source_system_id::text,me.source_customer_id)
                   IS DISTINCT FROM (e.app_id,e.payload->>'source_system_id',e.user_id))
           OR EXISTS (SELECT FROM control.customer_identity_member_export me
               JOIN staging.customer_profile p USING(standardized_record_id)
               WHERE (p.app_id,p.source_system_id,p.source_customer_id)
                   IS DISTINCT FROM (me.app_id,me.source_system_id,me.source_customer_id)
                 AND NOT EXISTS (SELECT FROM customer_050_published_active_alias alias
                   WHERE alias.standardized_record_id=me.standardized_record_id
                     AND (alias.published_app,alias.published_user,alias.source_system_id,
                          alias.raw_customer_id,alias.active_app)=
                         (me.app_id,me.source_customer_id,me.source_system_id,
                          me.raw_customer_id,p.app_id))) THEN
            RAISE EXCEPTION '050 published member ID ownership collision';
        END IF;
    END IF;
    -- A released ID may never be commandeered for a newly reconstructed
    -- profile, including the singleton-history shortcut. Fresh deterministic
    -- candidates must also be disjoint from every export and bridge version.
    IF to_regclass('control.customer_identity_member_export') IS NOT NULL THEN
        -- The earlier bridge ownership guard proves each ID has at most one
        -- logical owner (and export/bridge provenance was checked exactly).
        -- Deduplicate versioned bridge IDs before comparing historical owners:
        -- a raw ID join can multiply replay histories by publication versions.
        IF EXISTS (WITH bridge_owners AS MATERIALIZED
            (SELECT DISTINCT ON (standardized_record_id)
                standardized_record_id,app_id,source_system_id,source_customer_id
             FROM control.customer_identity_member_export
             ORDER BY standardized_record_id)
            SELECT FROM staging.customer_profile_history h
            JOIN bridge_owners me USING(standardized_record_id)
            WHERE (h.app_id,h.source_system_id,h.source_customer_id)
              IS DISTINCT FROM (me.app_id,me.source_system_id,me.source_customer_id)) THEN
            RAISE EXCEPTION '050 published member ID collides with historical owner';
        END IF;
    ELSE
        -- 041 bridge is optional in the owned 036-only fixture. Retain the
        -- payload-only proof when there is no typed immutable bridge.
        IF EXISTS (SELECT FROM staging.customer_profile_history h
            JOIN control.customer_identity_export e
              ON e.payload->>'standardized_record_id'=h.standardized_record_id::text
            WHERE (h.app_id,h.source_system_id::text,h.source_customer_id)
              IS DISTINCT FROM (e.app_id,e.payload->>'source_system_id',e.user_id)) THEN
            RAISE EXCEPTION '050 published ID collides with historical owner';
        END IF;
    END IF;
    -- Cross-app historical reuse is evidence of an alias, not an ownership
    -- decision. Missing keys receive a fresh tuple-bound ID below.
    IF EXISTS(SELECT FROM staging.customer_profile_history h WHERE h.app_id IS NOT NULL
       GROUP BY h.app_id,h.source_system_id,h.source_customer_id,h.batch_id
       HAVING count(*)>1) THEN
        RAISE EXCEPTION '050 ambiguous historical same-batch logical tuple';
    END IF;
    IF EXISTS(SELECT FROM staging.customer_profile p WHERE p.app_id IS NOT NULL
       GROUP BY p.app_id,p.source_system_id,p.source_customer_id HAVING count(*)>1) THEN
        RAISE EXCEPTION '050 ambiguous active logical tuple';
    END IF;
END $preflight$;

-- Retain primary key and original OID. Existing IDs keep their exact member
-- and export references. Only the obsolete raw UUID unique index is removed.
DROP INDEX staging.uq_customer_profile_raw_customer;
CREATE UNIQUE INDEX customer_profile_app_source_key
    ON staging.customer_profile(app_id,source_system_id,source_customer_id)
    WHERE app_id IS NOT NULL;
CREATE INDEX customer_profile_raw_provenance ON staging.customer_profile(raw_customer_id);

-- Backfill from latest exact typed observation. Single-owner singleton history
-- retains its ID; replay or cross-owner ambiguity receives a deterministic
-- fresh ID bound to the app/source/user and latest immutable batch/raw UUID.
DO $backfill$
DECLARE cols text; projection text;
BEGIN
    SELECT string_agg(format('%I',attname),',' ORDER BY attnum),
           string_agg(CASE WHEN attname='standardized_record_id' THEN 'choice.assigned_id'
               ELSE format('h.%I',attname) END,',' ORDER BY attnum)
      INTO cols,projection FROM pg_attribute
     WHERE attrelid='staging.customer_profile'::regclass AND attnum>0 AND NOT attisdropped;
    -- Avoid per-key full history scans when reconstructing large replay cohorts.
    CREATE TEMP TABLE customer_050_history_identity ON COMMIT DROP AS
      SELECT app_id,source_system_id,source_customer_id,
             count(DISTINCT standardized_record_id) AS logical_ids
      FROM staging.customer_profile_history WHERE app_id IS NOT NULL
      GROUP BY app_id,source_system_id,source_customer_id;
    CREATE UNIQUE INDEX ON customer_050_history_identity(app_id,source_system_id,source_customer_id);
    CREATE TEMP TABLE customer_050_id_owners ON COMMIT DROP AS
      SELECT standardized_record_id,
             count(DISTINCT (app_id,source_system_id,source_customer_id)) AS owner_count
      FROM staging.customer_profile_history WHERE app_id IS NOT NULL
      GROUP BY standardized_record_id;
    CREATE UNIQUE INDEX ON customer_050_id_owners(standardized_record_id);
    CREATE TEMP TABLE customer_050_released_ids ON COMMIT DROP AS
      SELECT DISTINCT (e.payload->>'standardized_record_id')::uuid AS standardized_record_id
      FROM control.customer_identity_export e;
    CREATE UNIQUE INDEX ON customer_050_released_ids(standardized_record_id);
    IF to_regclass('control.customer_identity_member_export') IS NOT NULL THEN
        -- The bridge may have millions of versions; a unique indexed insert
        -- avoids scanning the entire temporary export reservation per row.
        INSERT INTO customer_050_released_ids
          SELECT DISTINCT me.standardized_record_id
          FROM control.customer_identity_member_export me
          ON CONFLICT DO NOTHING;
    END IF;
    -- The released ID's validated owner is stable across immutable versions.
    -- Materialize it once: the final guard must not scan JSON export versions
    -- once for every active profile (and 041 may be absent).
    CREATE TEMP TABLE customer_050_released_owner ON COMMIT DROP AS
      SELECT DISTINCT (e.payload->>'standardized_record_id')::uuid AS standardized_record_id,
          e.app_id,e.payload->>'source_system_id' AS source_system_id,
          e.user_id AS source_customer_id,e.payload->>'raw_customer_id' AS raw_customer_id
      FROM control.customer_identity_export e;
    CREATE INDEX ON customer_050_released_owner(standardized_record_id);
    CREATE TEMP TABLE customer_050_missing_keys ON COMMIT DROP AS
      SELECT DISTINCT h.app_id,h.source_system_id,h.source_customer_id
      FROM staging.customer_profile_history h
      WHERE h.app_id IS NOT NULL AND NOT EXISTS (
        SELECT FROM staging.customer_profile p WHERE
          (p.app_id,p.source_system_id,p.source_customer_id)=
          (h.app_id,h.source_system_id,h.source_customer_id));
    CREATE UNIQUE INDEX ON customer_050_missing_keys(app_id,source_system_id,source_customer_id);
    -- Compute the latest missing observation once. The candidate and the
    -- inserted row must refer to the same frozen batch/raw provenance.
    CREATE TEMP TABLE customer_050_latest_missing ON COMMIT DROP AS
      SELECT DISTINCT ON (h.app_id,h.source_system_id,h.source_customer_id) h.*
      FROM staging.customer_profile_history h
      JOIN customer_050_missing_keys missing
        ON (missing.app_id,missing.source_system_id,missing.source_customer_id)=
           (h.app_id,h.source_system_id,h.source_customer_id)
      JOIN control.ingestion_batch b ON b.batch_id=h.batch_id
      ORDER BY h.app_id,h.source_system_id,h.source_customer_id,
               b.created_at DESC,b.batch_id DESC;
    -- The selected set is bounded by missing logical keys, rather than by
    -- the full historical replay count. Materialize both the decision and ID.
    CREATE TEMP TABLE customer_050_choices ON COMMIT DROP AS
      SELECT h.*,
        NOT (logical.logical_ids=1 AND id_owner.owner_count=1
          AND NOT EXISTS (SELECT FROM staging.customer_profile p
                          WHERE p.standardized_record_id=h.standardized_record_id)
          AND NOT EXISTS (SELECT FROM identity.customer_entity_member m
                          WHERE m.standardized_record_id=h.standardized_record_id)
          AND NOT EXISTS (SELECT FROM customer_050_released_ids reserved
                          WHERE reserved.standardized_record_id=h.standardized_record_id)
          AND NOT EXISTS (SELECT FROM customer_050_published_active_alias alias
                          WHERE (alias.published_app,alias.source_system_id,
                                 alias.published_user,alias.raw_customer_id)=
                                (h.app_id,h.source_system_id,h.source_customer_id,h.raw_customer_id)))
          AS needs_allocation,
        md5('050/customer-logical-member/v1:' ||
          length(h.app_id)::text || ':' || h.app_id || ':' ||
          h.source_system_id::text || ':' ||
          length(h.source_customer_id)::text || ':' || h.source_customer_id || ':' ||
          h.batch_id::text || ':' || h.raw_customer_id::text)::uuid AS candidate_id
      FROM customer_050_latest_missing h
      JOIN customer_050_history_identity logical
        ON (logical.app_id,logical.source_system_id,logical.source_customer_id)=
           (h.app_id,h.source_system_id,h.source_customer_id)
      JOIN customer_050_id_owners id_owner USING(standardized_record_id);
    -- A unique index catches two newly allocated keys hashing to one ID.
    -- Existing reservations are checked by indexed UUID lookups, never by
    -- one history heap scan for each of the 60k candidate keys.
    CREATE UNIQUE INDEX ON customer_050_choices
      ((CASE WHEN needs_allocation THEN candidate_id ELSE standardized_record_id END));
    IF EXISTS (
      SELECT FROM customer_050_choices choice
      WHERE choice.needs_allocation AND
        (EXISTS (SELECT FROM customer_050_released_ids reserved
                 WHERE reserved.standardized_record_id=choice.candidate_id)
         OR EXISTS (SELECT FROM customer_050_id_owners historical
                    WHERE historical.standardized_record_id=choice.candidate_id)
         OR EXISTS (SELECT FROM staging.customer_profile current_profile
                    WHERE current_profile.standardized_record_id=choice.candidate_id)
         OR EXISTS (SELECT FROM identity.customer_entity_member member
                    WHERE member.standardized_record_id=choice.candidate_id))
    ) THEN
       RAISE EXCEPTION '050 allocated ID collides with released or historical owner';
    END IF;
    projection := replace(projection, 'h.', 'choice.');
    EXECUTE format($sql$
      INSERT INTO staging.customer_profile(%s)
      SELECT %s FROM (
        SELECT choice.*,
          CASE WHEN choice.needs_allocation THEN choice.candidate_id
               ELSE choice.standardized_record_id END AS assigned_id
        FROM customer_050_choices choice
      ) choice
      $sql$,cols,projection);
END $backfill$;

-- Deterministic IDs are not a license to commandeer preexisting evidence.
DO $allocated_identity$
BEGIN
    IF EXISTS(SELECT FROM staging.customer_profile p
        JOIN staging.customer_profile_history h USING(standardized_record_id)
        WHERE p.app_id IS NOT NULL AND
          NOT EXISTS (SELECT FROM staging.customer_profile_history own
              WHERE own.standardized_record_id=p.standardized_record_id
                AND (own.app_id,own.source_system_id,own.source_customer_id)=
                    (p.app_id,p.source_system_id,p.source_customer_id))
          AND (p.app_id,p.source_system_id,p.source_customer_id) IS DISTINCT FROM
          (h.app_id,h.source_system_id,h.source_customer_id))
       OR EXISTS (SELECT FROM staging.customer_profile p
           JOIN customer_050_released_ids reserved USING(standardized_record_id)
           WHERE NOT EXISTS (SELECT FROM staging.customer_profile_history own
               WHERE own.standardized_record_id=p.standardized_record_id
                 AND (own.app_id,own.source_system_id,own.source_customer_id)=
                     (p.app_id,p.source_system_id,p.source_customer_id))
             AND NOT EXISTS (SELECT FROM customer_050_published_active_alias alias
               WHERE alias.standardized_record_id=p.standardized_record_id
                 AND (alias.active_app,alias.source_system_id,alias.published_user,
                      alias.raw_customer_id)=
                     (p.app_id,p.source_system_id,p.source_customer_id,p.raw_customer_id))
             -- The historical typed observation may carry a different ID
             -- from the resolver's released ID. An exact immutable export
             -- of this SAME active tuple proves ownership without inventing
             -- a history-ID equality (cross-app aliases use the gate above).
             AND NOT EXISTS (SELECT FROM customer_050_released_owner owner
               WHERE owner.standardized_record_id=p.standardized_record_id
                 AND (owner.app_id,owner.source_system_id,owner.source_customer_id,
                      owner.raw_customer_id)=
                     (p.app_id,p.source_system_id::text,p.source_customer_id,
                      p.raw_customer_id::text)))
       OR EXISTS(SELECT FROM staging.customer_profile p
           JOIN identity.customer_entity_member m USING(standardized_record_id)
           WHERE (p.source_system_id,p.source_customer_id) IS DISTINCT FROM
                 (m.source_system_id,m.source_customer_id)) THEN
        RAISE EXCEPTION '050 allocated ID collides with historical/member owner';
    END IF;
END $allocated_identity$;

